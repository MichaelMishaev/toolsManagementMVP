#!/usr/bin/env node

import { readFile, writeFile, watch } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(projectRoot, "design/design.md");
const outputPath = resolve(projectRoot, "mock/assets/design-tokens.css");
const applicationTemplatePath = resolve(projectRoot, "mock/assets/app.template.css");
const applicationOutputPath = resolve(projectRoot, "mock/assets/app.css");
const argumentsSet = new Set(process.argv.slice(2));

function toKebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[_\s]+/g, "-")
    .toLowerCase();
}

function flattenTokens(input, path = [], output = []) {
  for (const [key, value] of Object.entries(input)) {
    const nextPath = [...path, toKebabCase(key)];
    if (value && typeof value === "object" && !Array.isArray(value)) {
      flattenTokens(value, nextPath, output);
      continue;
    }

    if (!["string", "number"].includes(typeof value)) {
      throw new TypeError(`Unsupported token value at ${nextPath.join(".")}`);
    }

    output.push([`--${nextPath.join("-")}`, String(value)]);
  }

  return output;
}

function parseDesignTokens(documentText) {
  const match = documentText.match(/```design-tokens\s*\n([\s\S]*?)\n```/);
  if (!match) {
    throw new Error("No fenced design-tokens JSON block found in design/design.md");
  }

  const parsed = JSON.parse(match[1]);
  if (!parsed.tokens || typeof parsed.tokens !== "object") {
    throw new Error("The design-tokens block must contain a tokens object");
  }

  return parsed;
}

function createCss(parsed) {

  const declarations = flattenTokens(parsed.tokens)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");

  return [
    "/* Generated from design/design.md by scripts/sync-design-tokens.mjs. */",
    "/* Do not edit this file directly. */",
    ":root {",
    declarations,
    "}",
    ""
  ].join("\n");
}

function readToken(tokens, path) {
  return path.split(".").reduce((value, segment) => value?.[segment], tokens);
}

function renderApplicationCss(template, parsed) {
  return template.replace(/\{\{\s*([a-zA-Z0-9_.]+)\s*\}\}/g, (_, path) => {
    const value = readToken(parsed.tokens, path);
    if (!["string", "number"].includes(typeof value)) {
      throw new Error(`Unknown design token placeholder: ${path}`);
    }
    return String(value);
  });
}

async function build({ check = false } = {}) {
  const documentText = await readFile(sourcePath, "utf8");
  const parsed = parseDesignTokens(documentText);
  const nextCss = createCss(parsed);
  const applicationTemplate = await readFile(applicationTemplatePath, "utf8").catch(() => null);
  const nextApplicationCss = applicationTemplate
    ? renderApplicationCss(applicationTemplate, parsed)
    : null;

  if (check) {
    const currentCss = await readFile(outputPath, "utf8").catch(() => "");
    const currentApplicationCss = nextApplicationCss
      ? await readFile(applicationOutputPath, "utf8").catch(() => "")
      : null;
    if (currentCss !== nextCss || currentApplicationCss !== nextApplicationCss) {
      console.error("Generated design CSS is out of date. Run node scripts/sync-design-tokens.mjs");
      process.exitCode = 1;
      return;
    }
    console.log("Generated design CSS matches design/design.md and app.template.css");
    return;
  }

  await writeFile(outputPath, nextCss, "utf8");
  if (nextApplicationCss) {
    await writeFile(applicationOutputPath, nextApplicationCss, "utf8");
  }
  console.log("Generated mock/assets/design-tokens.css and mock/assets/app.css");
}

if (argumentsSet.has("--watch")) {
  await build();
  console.log("Watching design/design.md for token changes");
  const watcher = watch(sourcePath);
  for await (const event of watcher) {
    if (event.eventType !== "change") continue;
    try {
      await build();
    } catch (error) {
      console.error(error instanceof Error ? error.message : error);
    }
  }
} else {
  await build({ check: argumentsSet.has("--check") });
}
